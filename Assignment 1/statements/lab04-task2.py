# Multi-line statement using line continuation (\)
total = 10 + 20 + 30 + \
        40 + 50

print("Total using line continuation:", total)

# Multi-line statement using parentheses ()
sum_value = (
    10 +
    20 +
    30 +
    40 +
    50
)

print("Total using parentheses:", sum_value)
"""
Output:
Total using line continuation: 150
Total using parentheses: 150
"""